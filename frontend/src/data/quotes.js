/**
 * Returns a quote from the pool that changes deterministically every single day.
 * Based on the calendar day of the year (UTC/local date).
 */
export function getDailyQuote(quoteList = quotes) {
  if (!quoteList || quoteList.length === 0) {
    return { text: "Good writing doesn't demand attention. It earns it.", author: "Quill" };
  }

  const now = new Date();
  // Calculate day number since start of the epoch for smooth continuous rotation
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now - startOfYear;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Year offset ensures unique order across different years
  const yearOffset = (now.getFullYear() * 31) % quoteList.length;
  const quoteIndex = (dayOfYear + yearOffset) % quoteList.length;

  return quoteList[quoteIndex];
}
